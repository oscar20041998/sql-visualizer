it('analyzes an Oracle CREATE TABLE without a terminal semicolon', async () => {
  const result = await analyzeTable('CREATE TABLE employees (id NUMBER(10))', 'oracle');
  expect(result?.columns).toEqual([{ name: 'id', type: 'NUMBER(10)' }]);
});

it('preserves Oracle NUMBER precision and scale', async () => {
  const result = await analyzeTable('CREATE TABLE t (amount NUMBER(10,2));', 'oracle');
  expect(result?.columns).toEqual([{ name: 'amount', type: 'NUMBER(10,2)' }]);
});

it('rejects unsupported, invalid, and multiple Oracle statements', async () => {
  for (const sql of [
    'CREATE TABLE t (id NUMBER',
    'CREATE TABLE t (id NUMBER); CREATE TABLE u (id NUMBER);',
    'CREATE TABLE "HR"."Staff" ("Name" VARCHAR2(80));',
    'CREATE TABLE t (id NUMBER, created TIMESTAMP WITH TIME ZONE);',
    'CREATE TABLE t (name VARCHAR2(80 CHAR));',
  ]) {
    await expect(analyzeTable(sql, 'oracle')).resolves.toBeNull();
  }
});

it('recognizes Oracle DATE columns', async () => {
  const result = await analyzeTable('CREATE TABLE t (created DATE);', 'oracle');
  expect(result?.columns).toEqual([{ name: 'created', type: 'DATE' }]);
});

it('distinguishes Oracle foreign keys from primary keys despite parser metadata', async () => {
  const result = await analyzeTable(
    'CREATE TABLE HR.emp (id NUMBER PRIMARY KEY, dept_id NUMBER, CONSTRAINT fk FOREIGN KEY (dept_id) REFERENCES HR.dept(id));',
    'oracle'
  );
  expect(result?.details?.constraints).toContainEqual({
    type: 'FOREIGN KEY', name: 'fk', columns: ['dept_id'], reference: 'HR.dept (id)',
  });
  expect(result?.details?.constraints).toContainEqual({
    type: 'PRIMARY KEY', name: null, columns: ['id'], reference: null,
  });
});

it('extracts supported PostgreSQL inline references and identity', async () => {
  const result = await analyzeTable(
    "CREATE TABLE sales.staff (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL DEFAULT 'a', team_id INT REFERENCES sales.team(id));",
    'postgresql'
  );
  expect(result?.details?.columns.find((column) => column.name === 'id')?.identity).toBe('GENERATED BY DEFAULT AS IDENTITY');
  expect(result?.details?.columns.find((column) => column.name === 'name')?.defaultValue).toBe("'a'");
  expect(result?.details?.constraints).toContainEqual({
    type: 'FOREIGN KEY', name: null, columns: ['team_id'], reference: 'sales.team (id)',
  });
});

it('extracts SQL Server inline primary keys and explicitly declared nullability', async () => {
  const result = await analyzeTable('CREATE TABLE dbo.employees ([id] INT NOT NULL PRIMARY KEY, [name] NVARCHAR(80));', 'sqlserver');
  expect(result?.details?.constraints).toContainEqual({
    type: 'PRIMARY KEY', name: null, columns: ['id'], reference: null,
  });
  expect(result?.details?.columns.find((column) => column.name === 'id')?.nullable).toBe('NOT NULL');
  expect(result?.details?.columns.find((column) => column.name === 'name')?.nullable).toBeNull();
});

it('preserves declared column types in the sample employee table', async () => {
  const sql = readFileSync('src/sample/demo-create-table.sql', 'utf8');
  const result = await analyzeTable(sql, 'mysql');
  expect(result?.name).toBe('employees');
  expect(result?.columns).toHaveLength(12);
  expect(result?.columns).toContainEqual({ name: 'salary', type: 'DECIMAL(15,2)' });
  expect(result?.columns).toContainEqual({
    name: 'gender',
    type: "ENUM('MALE', 'FEMALE', 'OTHER')",
  });
  expect(result?.details?.columns).toContainEqual({
    name: 'id', nullable: 'NOT NULL', defaultValue: null, identity: 'AUTO_INCREMENT',
    comment: 'Primary key of employee',
  });
  expect(result?.details?.columns.find((column) => column.name === 'salary')?.defaultValue).toBe('0.00');
  expect(result?.details?.constraints).toContainEqual({
    type: 'FOREIGN KEY', name: 'fk_employees_department', columns: ['department_id'], reference: 'departments (id)',
  });
  expect(result?.details?.constraints).toContainEqual({
    type: 'PRIMARY KEY', name: 'pk_employees', columns: ['id'], reference: null,
  });
  expect(result?.details?.indexes).toContainEqual({
    type: 'FULLTEXT INDEX', name: 'ft_employees_name', columns: ['full_name'],
  });
  expect(result?.details?.indexes).toHaveLength(4);
  expect(result?.details?.options).toContainEqual({ name: 'ENGINE', value: 'INNODB' });
});

it('preserves escaped values in MySQL ENUM types', async () => {
  const result = await analyzeTable("CREATE TABLE t (v ENUM('O''Brien', 'a,b'));", 'mysql');
  expect(result?.columns).toEqual([{ name: 'v', type: "ENUM('O''Brien', 'a,b')" }]);
});
